//! Watches the Mac's clipboard for the history "clip" lists (clipboard.zig):
//! twice a second it asks whether anything was copied, and keeps the text
//! if so. What password managers mark concealed or transient is never
//! kept. The history lives in a file only this user can read, in
//! Nanolight's folder in Application Support.
const std = @import("std");
const nanoui = @import("nanoui");
const clipboard = @import("clipboard.zig");
const Live = @import("main.zig").Live;
const mac = @import("builtin").os.tag == .macos;

const every_ms = 500;
const file_name = "clipboard-history.txt";

pub const State = struct {
    history: ?clipboard.History = null,
    /// The pasteboard's count when last looked at.
    count: isize = 0,
    /// Where the history is kept; empty when there's nowhere.
    path_buf: [1024]u8 = undefined,
    path: []const u8 = "",
};

/// Reads the history kept before and starts watching (the Mac's only).
pub fn start(l: *Live) void {
    if (comptime !mac) return;
    const st = &l.clips;
    st.history = .{ .gpa = l.app.gpa };
    l.s.clips = &st.history.?;
    if (nanoui.path(l.app.gpa, .data, "Nanolight")) |dir| {
        defer l.app.gpa.free(dir);
        st.path = std.fmt.bufPrint(&st.path_buf, "{s}/{s}", .{ dir, file_name }) catch "";
    } else |_| {}
    if (st.path.len > 0) {
        if (std.Io.Dir.cwd().readFileAlloc(l.app.io, st.path, l.app.gpa, .limited(32 << 20))) |bytes| {
            defer l.app.gpa.free(bytes);
            st.history.?.decode(bytes);
        } else |_| {}
    }
    // What's on the clipboard now was copied before: kept from here on.
    st.count = nanoui.clipboard.changeCount();
    nanoui.App.after(every_ms, l, tick);
}

pub fn deinit(l: *Live) void {
    if (l.clips.history) |*h| h.deinit();
    l.clips.history = null;
    l.s.clips = null;
}

fn tick(ctx: ?*anyopaque) callconv(.c) void {
    const l: *Live = @ptrCast(@alignCast(ctx.?));
    defer nanoui.App.after(every_ms, l, tick);
    const st = &l.clips;
    const h = if (st.history) |*x| x else return;
    const now = nanoui.clipboard.changeCount();
    if (now == st.count) return;
    st.count = now;
    if (concealed()) return;
    const text = (nanoui.clipboard.readText(l.app.gpa) catch null) orelse return;
    defer l.app.gpa.free(text);
    // Copied over while it was read: the marks looked at may not be this
    // text's. The next tick looks at the new one.
    if (nanoui.clipboard.changeCount() != now or concealed()) return;
    if (!h.add(text, @import("account.zig").now())) return;
    save(l);
    // Listed now: the rows again, with it.
    l.s.clipsChanged();
    if (l.window) |w| w.redraw();
}

/// The history to its file, readable by this user alone, whole or not at
/// all.
fn save(l: *Live) void {
    const st = &l.clips;
    const h = if (st.history) |*x| x else return;
    if (st.path.len == 0) return;
    var out: std.Io.Writer.Allocating = .init(l.app.gpa);
    defer out.deinit();
    h.encode(&out.writer) catch return;
    const io = l.app.io;
    const dir = std.Io.Dir.cwd();
    var af = dir.createFileAtomic(io, st.path, .{ .permissions = .fromMode(0o600), .replace = true }) catch return;
    defer af.deinit(io);
    af.file.writeStreamingAll(io, out.written()) catch return;
    af.replace(io) catch return;
}

/// Password managers mark what they copy (nspasteboard.org): it isn't kept.
fn concealed() bool {
    const objc = nanoui.objc;
    const pool = objc.Pool.push();
    defer pool.pop();
    const pb = objc.msg(objc.Object, objc.class("NSPasteboard"), "generalPasteboard", .{});
    // No types to look at: not kept.
    const types = objc.msg(?objc.Object, pb, "types", .{}) orelse return true;
    const marks = [_][]const u8{
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    };
    for (marks) |m| if (objc.msg(objc.BOOL, types, "containsObject:", .{objc.nsString(m)})) return true;
    return false;
}
